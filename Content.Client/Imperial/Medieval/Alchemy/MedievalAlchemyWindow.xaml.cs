        private PanelContainer CreateAlchemyBottleRow(MedievalAlchemyBottleInfo bottle)
        {
            var row = new BoxContainer
            {
                Orientation = LayoutOrientation.Horizontal, HorizontalExpand = true, SeparationOverride = 8, Margin = new Thickness(5)
            };

            var sprite = new SpriteView(_entityManager.GetEntity(bottle.Entity), _entityManager)
            {
                MinSize = new Vector2(48, 48),
                MaxSize = new Vector2(48, 48),
                Stretch = SpriteView.StretchMode.Fit
            };

            row.AddChild(sprite);

            var information = new BoxContainer
            {
                Orientation = LayoutOrientation.Vertical, HorizontalExpand = true, SeparationOverride = 4
            };

            information.AddChild(new Label
            {
                Text = $"{bottle.SlotIndex + 1}. {bottle.Name}"
            });

            information.AddChild(new Label
            {
                Text = Loc.GetString("medieval-alchemy-window-volume", ("current", bottle.Volume), ("capacity", bottle.Capacity))
            });

            information.AddChild(CreateAlchemyReagentBar(bottle));

            foreach (var reagent in bottle.Reagents)
            {
                if (reagent.Quantity <= 0)
                    continue;

                _prototypeManager.TryIndex(reagent.Reagent.Prototype, out ReagentPrototype? proto);

                var reagentColor = proto?.SubstanceColor
                    ?? Color.White;

                var reagentName = proto?.LocalizedName
                    ?? reagent.Reagent.Prototype.ToString();

                var reagentRow = new BoxContainer
                {
                    Orientation = LayoutOrientation.Horizontal, SeparationOverride = 5
                };

                reagentRow.AddChild(new PanelContainer
                {
                    MinSize = new Vector2(9, 9), PanelOverride = new StyleBoxFlat(reagentColor)
                });

                reagentRow.AddChild(new Label
                {
                    Text = Loc.GetString("medieval-alchemy-window-reagent-quantity", ("name", reagentName), ("amount", reagent.Quantity))
                });

                information.AddChild(reagentRow);
            }

            row.AddChild(information);

            var ejectButton = new Button
            {
                Text = Loc.GetString("medieval-alchemy-window-eject"),
                MinSize = new Vector2(85, 28)
            };

            ejectButton.OnPressed += _ => OnAlchemyBottleEjectPressed?.Invoke(bottle.Entity);

            row.AddChild(ejectButton);

            return new PanelContainer
            {
                PanelOverride = new StyleBoxFlat(Color.FromHex("#202025")), Children = { row }
            };
        }

        private Control CreateAlchemyReagentBar(MedievalAlchemyBottleInfo bottle)
        {
            const float barWidth = 240f;
            const float barHeight = 12f;

            var bar = new BoxContainer
            {
                Orientation = LayoutOrientation.Horizontal, SeparationOverride = 0, MinSize = new Vector2(barWidth, barHeight)
            };

            var capacity = bottle.Capacity.Float();
            var remainingWidth = barWidth;

            if (capacity > 0f)
            {
                foreach (var reagent in bottle.Reagents)
                {
                    var amount = reagent.Quantity.Float();

                    if (amount <= 0f || remainingWidth <= 0f)
                        continue;

                    _prototypeManager.TryIndex(reagent.Reagent.Prototype, out ReagentPrototype? proto);

                    var color = proto?.SubstanceColor
                        ?? Color.White;

                    var width = Math.Clamp(barWidth * amount / capacity, 0f, remainingWidth);

                    if (width <= 0f)
                        continue;

                    bar.AddChild(new PanelContainer
                    {
                        MinSize = new Vector2(width, barHeight),
                        PanelOverride = new StyleBoxFlat(color)
                    });

                    remainingWidth -= width;
                }
            }

            if (remainingWidth > 0f)
            {
                bar.AddChild(new PanelContainer
                {
                    MinSize = new Vector2(remainingWidth, barHeight), PanelOverride = new StyleBoxFlat(Color.FromHex("#34343A"))
                });
            }

            return bar;
        }

