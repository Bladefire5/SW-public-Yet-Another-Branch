            foreach (var (text, amount, styleClass) in buttonConfigs)
            {
                var reagentTransferButton = MakeReagentButton(text, amount, reagent, isBuffer, styleClass);
                buttons.Add(reagentTransferButton);
            }

            return buttons;
        }

        /// <summary>
        /// Update the UI state when new state data is received from the server.
        /// </summary>
        /// <param name="state">State data sent by the server.</param>
        public void UpdateState(BoundUserInterfaceState state)
        {
            var castState = (ChemMasterBoundUserInterfaceState)state;

            if (castState.UpdateLabel)
                LabelLine = GenerateLabel(castState);

            // Ensure the Panel Info is updated, including UI elements for Buffer Volume, Output Container and so on
            UpdatePanelInfo(castState);

            BufferCurrentVolume.Text = $" {castState.BufferCurrentVolume?.Int() ?? 0}u";

            InputEjectButton.Disabled = castState.InputContainerInfo is null;
            OutputEjectButton.Disabled = castState.OutputContainerInfo is null;
            CreateBottleButton.Disabled = castState.OutputContainerInfo?.Reagents == null;
            CreatePillButton.Disabled = castState.OutputContainerInfo?.Entities == null;

            UpdateDosageFields(castState);
        }

        //assign default values for pill and bottle fields.
        private void UpdateDosageFields(ChemMasterBoundUserInterfaceState castState)
        {
            var output = castState.OutputContainerInfo;
            var remainingCapacity = output is null ? 0 : (output.MaxVolume - output.CurrentVolume).Int();
            var holdsReagents = output?.Reagents != null;
            var pillNumberMax = holdsReagents ? 0 : remainingCapacity;
            var bottleAmountMax = holdsReagents ? remainingCapacity : 0;
            var bufferVolume = castState.BufferCurrentVolume?.Int() ?? 0;

            PillDosage.Value = (int)Math.Min(bufferVolume, castState.PillDosageLimit);

            PillTypeButtons[castState.SelectedPillType].Pressed = true;

            PillNumber.IsValid = x => x >= 0 && x <= pillNumberMax;
            PillDosage.IsValid = x => x > 0 && x <= castState.PillDosageLimit;
            BottleDosage.IsValid = x => x >= 0 && x <= bottleAmountMax;

            if (PillNumber.Value > pillNumberMax)
                PillNumber.Value = pillNumberMax;
            if (BottleDosage.Value > bottleAmountMax)
                BottleDosage.Value = bottleAmountMax;

            // Avoid division by zero
            if (PillDosage.Value > 0)
            {
                PillNumber.Value = Math.Min(bufferVolume / PillDosage.Value, pillNumberMax);
            }
            else
            {
                PillNumber.Value = 0;
            }

            BottleDosage.Value = Math.Min(bottleAmountMax, bufferVolume);
        }
        /// <summary>
        /// Generate a product label based on reagents in the buffer.
        /// </summary>
        /// <param name="state">State data sent by the server.</param>
        private string GenerateLabel(ChemMasterBoundUserInterfaceState state)
        {
            if (state.BufferCurrentVolume == 0)
                return "";

            var reagent = state.BufferReagents.OrderBy(r => r.Quantity).First().Reagent;
            _prototypeManager.TryIndex(reagent.Prototype, out ReagentPrototype? proto);
            return proto?.LocalizedName ?? "";
        }

        /// <summary>
        /// Update the container, buffer, and packaging panels.
        /// </summary>
        /// <param name="state">State data for the dispenser.</param>
        private void UpdatePanelInfo(ChemMasterBoundUserInterfaceState state)
        {
            BufferTransferButton.Pressed = state.Mode == ChemMasterMode.Transfer;
            BufferDiscardButton.Pressed = state.Mode == ChemMasterMode.Discard;

            BuildContainerUI(InputContainerInfo, state.InputContainerInfo, true);
            BuildContainerUI(OutputContainerInfo, state.OutputContainerInfo, false);

            BufferInfo.Children.Clear();

            // This has to happen here due to people possibly
            // setting sorting before putting any chemicals
            BufferSortButton.Text = state.SortingType switch
            {
                ChemMasterSortingType.Alphabetical => Loc.GetString("chem-master-window-sort-type-alphabetical"),
                ChemMasterSortingType.Quantity => Loc.GetString("chem-master-window-sort-type-quantity"),
                ChemMasterSortingType.Latest => Loc.GetString("chem-master-window-sort-type-latest"),
                _ => Loc.GetString("chem-master-window-sort-type-none")
            };


            if (!state.BufferReagents.Any())
            {
                BufferInfo.Children.Add(new Label { Text = Loc.GetString("chem-master-window-buffer-empty-text") });

                return;
            }

            var bufferHBox = new BoxContainer
            {
                Orientation = LayoutOrientation.Horizontal
            };
            BufferInfo.AddChild(bufferHBox);

            var bufferLabel = new Label { Text = $"{Loc.GetString("chem-master-window-buffer-label")} " };
            bufferHBox.AddChild(bufferLabel);
            var bufferVol = new Label
            {
                Text = $"{state.BufferCurrentVolume}u",
                StyleClasses = { StyleNano.StyleClassLabelSecondaryColor }
            };
            bufferHBox.AddChild(bufferVol);

            // This sets up the needed data for sorting later in a list
            // Its done this way to not repeat having to use same code twice (once for sorting
            // and once for displaying)
            var reagentList = new List<(ReagentId reagentId, string name, Color color, FixedPoint2 quantity)>();
            foreach (var (reagent, quantity) in state.BufferReagents)
            {
                var reagentId = reagent;
                _prototypeManager.TryIndex(reagentId.Prototype, out ReagentPrototype? proto);
                var name = proto?.LocalizedName ?? Loc.GetString("chem-master-window-unknown-reagent-text");
                var reagentColor = proto?.SubstanceColor ?? default(Color);
                reagentList.Add(new(reagentId, name, reagentColor, quantity));
            }

            // We sort here since we need sorted list to be filled first.
            // You can easily add any new params you need to it.
            switch (state.SortingType)
            {
                case ChemMasterSortingType.Alphabetical:
                    reagentList = reagentList.OrderBy(x => x.name).ToList();
                    break;

                case ChemMasterSortingType.Quantity:
                    reagentList = reagentList.OrderByDescending(x => x.quantity).ToList();
                    break;
                case ChemMasterSortingType.Latest:
                    reagentList = Enumerable.Reverse(reagentList).ToList();
                    break;

                case ChemMasterSortingType.None:
                default:
                    // This case is pointless but it is there for readability
                    break;
            }

            // initialises rowCount to allow for striped rows
            var rowCount = 0;
            foreach (var reagent in reagentList)
            {
                BufferInfo.Children.Add(BuildReagentRow(reagent.color, rowCount++, reagent.name, reagent.reagentId, reagent.quantity, true, true));
            }
        }

        private void BuildContainerUI(Control control, ContainerInfo? info, bool addReagentButtons)
        {
            control.Children.Clear();

            if (info is null)
            {
                control.Children.Add(new Label
                {
                    Text = Loc.GetString("chem-master-window-no-container-loaded-text")
                });
                return;
            }

            // Name of the container and its fill status (Ex: 44/100u)
            control.Children.Add(new BoxContainer
            {
                Orientation = LayoutOrientation.Horizontal,
                Children =
                {
                    new Label { Text = $"{info.DisplayName}: " },
                    new Label
                    {
                        Text = $"{info.CurrentVolume}/{info.MaxVolume}",
                        StyleClasses = { StyleNano.StyleClassLabelSecondaryColor }
                    }
                }
            });
            // Initialises rowCount to allow for striped rows
            var rowCount = 0;

            // Handle entities if they are not null
            if (info.Entities != null)
            {
                foreach (var (id, quantity) in info.Entities.Select(x => (x.Id, x.Quantity)))
                {
                    control.Children.Add(BuildReagentRow(default(Color), rowCount++, id, default(ReagentId), quantity, false, addReagentButtons));
                }
            }

            // Handle reagents if they are not null
            if (info.Reagents != null)
            {
                foreach (var reagent in info.Reagents)
                {
                    _prototypeManager.TryIndex(reagent.Reagent.Prototype, out ReagentPrototype? proto);
                    var name = proto?.LocalizedName ?? Loc.GetString("chem-master-window-unknown-reagent-text");
                    var reagentColor = proto?.SubstanceColor ?? default(Color);

                    control.Children.Add(BuildReagentRow(reagentColor, rowCount++, name, reagent.Reagent, reagent.Quantity, false, addReagentButtons));
                }
            }
        }
        /// <summary>
        /// Take reagent/entity data and present rows, labels, and buttons appropriately. todo sprites?
        /// </summary>
        private Control BuildReagentRow(Color reagentColor, int rowCount, string name, ReagentId reagent, FixedPoint2 quantity, bool isBuffer, bool addReagentButtons)
        {
            //Colors rows and sets fallback for reagentcolor to the same as background, this will hide colorPanel for entities hopefully
            var rowColor1 = Color.FromHex("#1B1B1E");
            var rowColor2 = Color.FromHex("#202025");
            var currentRowColor = (rowCount % 2 == 1) ? rowColor1 : rowColor2;
            if ((reagentColor == default(Color)) | (!addReagentButtons))
            {
                reagentColor = currentRowColor;
            }
            //this calls the separated button builder, and stores the return to render after labels
            var reagentButtonConstructors = CreateReagentTransferButtons(reagent, isBuffer, addReagentButtons);

            // Create the row layout with the color panel
            var rowContainer = new BoxContainer
            {
                Orientation = LayoutOrientation.Horizontal,
                Children =
                {
                    new Label { Text = $"{name}: " },
                    new Label
                    {
                        Text = $"{quantity}u",
                        StyleClasses = { StyleNano.StyleClassLabelSecondaryColor }
                    },

                    // Padding
                    new Control { HorizontalExpand = true },
                    // Colored panels for reagents
                    new PanelContainer
                    {
                        Name = "colorPanel",
                        VerticalExpand = true,
                        MinWidth = 4,
                        PanelOverride = new StyleBoxFlat
                        {
                            BackgroundColor = reagentColor
                        },
                        Margin = new Thickness(0, 1)
                    }
                }
            };

            // Add the reagent buttons after the color panel
            foreach (var reagentTransferButton in reagentButtonConstructors)
            {
                rowContainer.AddChild(reagentTransferButton);
            }
            //Apply panencontainer to allow for striped rows
            return new PanelContainer
            {
                PanelOverride = new StyleBoxFlat(currentRowColor),
                Children = { rowContainer }
            };
        }
        private const int MaxAlchemyDosageCents = 20000; // 200.00u


        private static void ConfigureAlchemyDosage(LineEdit input, Button minus, Button plus, int maxCents = MaxAlchemyDosageCents)
        {
            input.IsValid = text => text == string.Empty || text == "." ||
            (TryParseAlchemyCents(text, out var cents) && cents <= maxCents);

            minus.OnPressed += _ => StepAlchemyDosage(input, -1, maxCents);
            plus.OnPressed += _ => StepAlchemyDosage(input, 1, maxCents);
        }

        private static void StepAlchemyDosage(LineEdit input, int direction, int maxCents)
        {
            var current = TryParseAlchemyCents(input.Text, out var cents)
            ? cents
            : 0;

            var next = Math.Clamp(current + direction, 0, maxCents);

            input.Text = (next / 100m).ToString("0.00", CultureInfo.InvariantCulture);
        }


        private static bool TryParseAlchemyCents(string text, out int cents)
        {
            cents = 0;

            if (string.IsNullOrEmpty(text))
                return false;

            var decimalIndex = text.IndexOf('.');

            if (decimalIndex >= 0 && text.Length - decimalIndex - 1 > 2)
                return false;

            if (!decimal.TryParse(text, NumberStyles.AllowDecimalPoint, CultureInfo.InvariantCulture, out var value))
                return false;

            if (value < 0m || value > 200m)
                return false;

            var scaled = value * 100m;

            if (scaled != decimal.Truncate(scaled))
                return false;

            cents = (int)scaled;
            return true;
        }

        public bool TryGetBottleDosages(out int potionCents, out int waterCents)
        {
            var validPotion = TryParseAlchemyCents(BottlePotionDosage.Text, out potionCents);

            var validWater = TryParseAlchemyCents(BottleWaterDosage.Text, out waterCents);

            return validPotion && validWater;
        }

        public bool TryGetBolusDosage(out int potionCents)
        {
            return TryParseAlchemyCents(BolusPotionDosage.Text, out potionCents)
                && potionCents > 0 && potionCents <= 1000;
        }

        private void UpdateAlchemyBolusButtonState()
        {
            var count = BolusCount.Value;

            CreateBolusButton.Disabled = !TryGetBolusDosage(out _) || count < 1 || count > 10 || count > _bolusFreeCapacity;
        }

        private void UpdateAlchemyFillButtonState()
        {
            var validAmounts = TryGetBottleDosages(out var potionCents, out var waterCents);

            var validDosage = validAmounts && potionCents > 0 && waterCents >= 0 && potionCents + waterCents <= MaxAlchemyDosageCents;

            var hasSelectedBottles = GetSelectedAlchemyBottleSlots().Length > 0;

            FillBottlesButton.Disabled = !validDosage || !hasSelectedBottles;
        }

        private void UpdateAlchemyBottleSlots(MedievalAlchemyUiState state)
        {
            for (var slot = 0; slot < _alchemySlotButtons.Length; slot++)
            {
                NetEntity? occupant = null;

                foreach (var bottle in state.Bottles)
                {
                    if (bottle.SlotIndex != slot)
                        continue;

                    occupant = bottle.Entity;
                    break;
                }

                var button = _alchemySlotButtons[slot];

                if (!Equals(_alchemySlotOccupants[slot], occupant))
                {
                    button.Pressed = false;
                }

                _alchemySlotOccupants[slot] = occupant;

                button.Disabled = occupant == null;
            }

            UpdateAlchemyFillButtonState();
        }

        public int[] GetSelectedAlchemyBottleSlots()
        {
            var selectedSlots = new List<int>();

            for (var slot = 0; slot < _alchemySlotButtons.Length; slot++)
            {
                var button = _alchemySlotButtons[slot];

                if (button.Disabled || !button.Pressed || _alchemySlotOccupants[slot] == null)
                {
                    continue;
                }

                selectedSlots.Add(slot);
            }

            return selectedSlots.ToArray();
        }

        public NetEntity[] GetSelectedAlchemyBottleEntities()
        {
            List<NetEntity> bottles = [];

            foreach (var slot in GetSelectedAlchemyBottleSlots())
            {
                if (_alchemySlotOccupants[slot] is not { } bottle)
                    continue;

                bottles.Add(bottle);
            }

            return bottles.ToArray();
        }

        public void UpdateAlchemyBottles(MedievalAlchemyUiState state)
        {
            BottleList.DisposeAllChildren();

            BottleCountLabel.Text = $"{state.Bottles.Length} / {state.MaxBottles}";

            WaterReservoirLabel.Text = $"{state.WaterVolume} / {state.WaterCapacity}u";
            NutrimentReservoirLabel.Text = $"{state.NutrimentVolume} / {state.NutrimentCapacity}u";
            InputBeakerVolumeLabel.Text = Loc.GetString("medieval-alchemy-window-volume", ("current", state.InputVolume), ("capacity", state.InputCapacity));
            PotionBufferVolumeLabel.Text = $"{state.BufferVolume}";

            UpdateAlchemyBottleSlots(state);
            UpdateAlchemyBolusBottle(state.BolusBottle);

            _bolusFreeCapacity = state.BolusBottle is { } bolusBottle
            ? Math.Max(0, bolusBottle.Capacity - bolusBottle.Count)
            : 0;

            UpdateAlchemyBolusButtonState();

            if (state.Bottles.Length == 0)
            {
                BottleList.AddChild(new Label
                {
                    Text = Loc.GetString("medieval-alchemy-window-no-bottles")
                });

                return;
            }

            foreach (var bottle in state.Bottles.OrderBy(b => b.SlotIndex))
            {
                BottleList.AddChild(CreateAlchemyBottleRow(bottle));
            }
        }

